/// The attestation digest a `record_matching` record actually stamps, READ BACK
/// from that record rather than indexed out of the pinned binding table.
/// RR-1b APPENDED a second digest to that list, and a `[0]` is a positional bet
/// on the order of a list that grows — a reorder would silently re-aim these
/// fixtures at a different attestation. Derived at point of use, with
/// membership in the pinned list asserted rather than assumed.
fn stamped_digest(record: &str) -> String {
    let d = record
        .lines()
        .find_map(|l| l.strip_prefix("provenance = "))
        .map(|v| v.trim().trim_matches('"').to_string())
        .expect("a record_matching record stamps a provenance line");
    assert!(
        genesis_attestation_digests().contains(&d.as_str()),
        "the stamped digest must be a PINNED attestation digest: {d}"
    );
    d
}

/// A record over the given input set in which every literal role is `PENDING`
/// (the cross-bound role stays cross-bound — `PENDING` there is `GP1-binding-*`).
fn pending_record(m: &str, t: &str, v: &str) -> String {
    let resolved = record_matching(m, t, v, false).expect("record_matching");
    // B-5: the record no longer stamps ONE digest on every role, so the retain
    // condition can no longer be "equals the record's digest" — that would have
    // silently started blanking the provenance of every role not attested by
    // whichever digest happened to appear first. Retain any PINNED digest; the
    // mutation being made here is to the PRINCIPALS, not the attestations.
    let pinned = genesis_attestation_digests();
    resolved
        .lines()
        .map(|l| {
            if l.starts_with("principal  = ") {
                "principal  = \"PENDING\"".to_string()
            } else if let Some(val) = l.strip_prefix("provenance = ") {
                if pinned.contains(&val.trim().trim_matches('"')) {
                    l.to_string()
                } else {
                    "provenance = \"PENDING\"".to_string()
                }
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

/// The number of `[role.*]` entries in a record text.
fn role_count(record: &str) -> usize {
    record.lines().filter(|l| l.starts_with("[role.")).count()
}

/// Rewrite ONE role's `principal` line in a record, anchored on the role HEADER
/// rather than on the value that role happens to hold. RR-1a is exactly why:
/// a mutation keyed on `principal  = "PENDING"` silently stopped applying the
/// moment the role was resolved.
fn set_record_principal(record: &str, role: &str, value: &str) -> String {
    let header = format!("[role.{role}]\n");
    let start = record
        .find(&header)
        .unwrap_or_else(|| panic!("record has no [role.{role}]"));
    let body = start + header.len();
    let line_end = body + record[body..].find('\n').expect("role entry has a second line");
    let line = &record[body..line_end];
    assert!(
        line.starts_with("principal  = ") || line.starts_with("binding    = "),
        "[role.{role}]'s first field must be `principal` or `binding`, found: {line}"
    );
    format!("{}principal  = \"{}\"{}", &record[..body], value, &record[line_end..])
}

/// Delete a whole `[role.X]` entry, anchored on the header.
fn remove_record_role(record: &str, role: &str) -> String {
    let header = format!("[role.{role}]\n");
    let start = record
        .find(&header)
        .unwrap_or_else(|| panic!("record has no [role.{role}]"));
    let end = record[start + header.len()..]
        .find("\n[")
        .map(|o| start + header.len() + o + 1)
        .unwrap_or(record.len());
    format!("{}{}", &record[..start], &record[end..])
}

