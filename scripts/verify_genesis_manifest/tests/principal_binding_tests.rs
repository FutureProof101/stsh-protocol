/// M-1: a COHERENT substitution — well-formed, distinct, non-placeholder,
/// identical across all three inputs, every coherence check green — with the
/// record UNCHANGED. This is the attack that passed the entire pre-R-3 gate.
#[test]
fn ac1_coherent_substitution_reds_at_gp2() {
    let (m, t, v) = resolved_set();
    let rec = record_matching(&m, &t, &v, true).unwrap();

    // Substitute EVERY non-cross-bound role's principal, coherently, everywhere.
    let manifest: Manifest = toml::from_str(&m).unwrap();
    let mut originals: Vec<String> = Vec::new();
    for a in manifest.allocation.iter() {
        if !originals.contains(&a.principal) {
            originals.push(a.principal.clone());
        }
    }
    let (mut m2, mut t2, mut v2) = (m.clone(), t.clone(), v.clone());
    let mut substituted_roles: Vec<String> = Vec::new();
    for (i, orig) in originals.iter().enumerate() {
        let new = attacker_principal(i as u8).to_text();
        m2 = m2.replace(orig.as_str(), &new);
        t2 = t2.replace(orig.as_str(), &new);
        v2 = v2.replace(orig.as_str(), &new);
    }
    for a in manifest.allocation.iter() {
        if !substituted_roles.contains(&a.principal_role) {
            substituted_roles.push(a.principal_role.clone());
        }
    }
    assert_ne!(m2, m, "mutation must apply");

    let checks = run_pinned(&m2, &t2, &v2, Some(&rec), &sha256_hex(rec.as_bytes()));

    // Every COHERENCE check is still green — that is the point of the finding.
    for name in names(&checks) {
        if name.starts_with("D1")
            || name.starts_with("D5")
            || name.starts_with("D7")
            || name.starts_with("D8")
            || name.starts_with("DP3-")
            || name.starts_with("V1")
            || name.starts_with("V2")
        {
            assert_passes(&checks, &name);
        }
    }
    // …and the substitution is caught at GP2, for every substituted role.
    for role in substituted_roles.iter() {
        assert_fails(&checks, &format!("GP2-value-{role}"));
    }
    // Control: the SAME substitution with a MATCHING record is green.
    let rec2 = record_matching(&m2, &t2, &v2, true).unwrap();
    let control = run(&m2, &t2, &v2, Some(&rec2));
    assert!(failing(&control).is_empty(), "matching-record control must be GREEN: {:?}", failing(&control));
}

