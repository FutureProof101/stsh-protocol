/// Anti-vacuity for every RED below: a legitimate RR-1 — every placeholder
/// replaced, the cross-bound role at the real Vault value, a matching record,
/// the pin regenerated — is GREEN on the FULL surface including `GP0`..`GP6`.
/// Without this, "the gate is RED" would prove nothing about the mechanism.
#[test]
fn ac0_matching_record_on_a_resolved_set_is_green() {
    let (m, t, v) = resolved_set();
    let rec = record_matching(&m, &t, &v, true).unwrap();
    let checks = run(&m, &t, &v, Some(&rec));
    assert!(failing(&checks).is_empty(), "resolved set + matching record must be GREEN: {:?}", failing(&checks));
    // The GP family genuinely RAN — a green run with no GP checks emitted would
    // satisfy the assertion above while proving nothing.
    let gp: Vec<String> = names(&checks).into_iter().filter(|n| n.starts_with("GP")).collect();
    assert!(gp.iter().any(|n| n == "GP0-record"), "GP0 must run");
    assert!(gp.iter().any(|n| n == "GP4-distinct"), "GP4 must run");
    assert!(gp.iter().any(|n| n == "GP6-record-pin"), "GP6 must run");
    assert_eq!(
        gp.iter().filter(|n| n.starts_with("GP2-value-")).count(),
        census_entries(),
        "all {} census roles must be evaluated by GP2 once resolved",
        census_entries()
    );
}

