    // set is EXACTLY EMPTY. This is a hard assertion, not the pre-RR-1b
    // disjunct — a disjunct with an `|| f.is_empty()` arm could no longer
    // distinguish "RR-1b landed" from "a role silently went PENDING again",
    // since the derived `expected` above would follow either way.
    assert!(
        pending_roles.is_empty(),
        "no genesis role may remain PENDING after RR-1b: {pending_roles:?}"
    );
    assert!(f.is_empty(), "the committed failing set must be EXACTLY EMPTY after RR-1b: {f:?}");
