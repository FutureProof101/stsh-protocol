/// The anonymous principal is deliberately ACCEPTED by
/// `principal_bytes_rejection_reason` (lane A-4 carried it as finding A-4-F1),
/// so it passes DP3 at base. GP3 is where it is refused.
#[test]
fn ac2_anonymous_and_management_are_forbidden_at_gp3() {
    // `dp3_also_fires` differs on purpose. The anonymous principal decodes to the
    // single byte 0x04, which `principal_bytes_rejection_reason` deliberately
    // ACCEPTS (lane A-4 carried that as finding A-4-F1) — so DP3 is GREEN on it
    // and GP3 is the ONLY control. The management canister decodes to zero
    // bytes, which limb 3 already rejects as "empty principal", so DP3 fires
    // there too. Asserting one behaviour for both would hide which check is
    // actually doing the work.
    for (forbidden, dp3_also_fires) in [("2vxsx-fae", false), ("aaaaa-aa", true)] {
        let (m, t, v) = resolved_set();
        let manifest: Manifest = toml::from_str(&m).unwrap();
        let target = manifest.allocation[1].principal.clone();
        let role = manifest.allocation[1].principal_role.clone();
        assert_eq!(role, "INSURANCE_MULTISIG");
        let (m2, t2, v2) = (
            m.replace(&target, forbidden),
            t.replace(&target, forbidden),
            v.replace(&target, forbidden),
        );
        // Written coherently into the record too — so ONLY the denylist can catch it.
        let rec = record_matching(&m2, &t2, &v2, true).unwrap();
        let checks = run(&m2, &t2, &v2, Some(&rec));
        assert_passes(&checks, &format!("GP2-value-{role}"));
        if dp3_also_fires {
            assert_fails(&checks, "DP3-manifest-alloc-1-insurance");
        } else {
            assert_passes(&checks, "DP3-manifest-alloc-1-insurance");
        }
        assert_fails(&checks, &format!("GP3-forbidden-{role}"));
    }
}

