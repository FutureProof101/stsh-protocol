fn failing(checks: &[CheckResult]) -> Vec<String> {
    checks.iter().filter(|c| !c.pass).map(|c| c.name.clone()).collect()
}

fn names(checks: &[CheckResult]) -> Vec<String> {
    checks.iter().map(|c| c.name.clone()).collect()
}

fn assert_fails(checks: &[CheckResult], name: &str) {
    let c = checks.iter().find(|c| c.name == name);
    assert!(c.is_some(), "check {name} was not emitted at all; failing set = {:?}", failing(checks));
    assert!(!c.unwrap().pass, "check {name} PASSED; expected FAIL. detail = {}", c.unwrap().detail);
}

fn assert_passes(checks: &[CheckResult], name: &str) {
    let c = checks.iter().find(|c| c.name == name);
    assert!(c.is_some(), "check {name} was not emitted at all");
    assert!(c.unwrap().pass, "check {name} FAILED; expected PASS. detail = {}", c.unwrap().detail);
}

/// A deterministic, VALID, non-placeholder principal that is distinct from every
/// principal any fixture uses. Derived, never hardcoded, so its checksum cannot
/// be wrong.
fn attacker_principal(i: u8) -> Principal {
    Principal::from_slice(&[0xA7, 0xBE, 0xEF, 0, 0, 0, 0, i, 0x01])
}

